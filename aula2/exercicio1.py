#Escreva um programa que peça à pessoas usuária para fornecer dois números e exibir o número maior
numero1 = int(input('Digite o primeiro número: '))
numero2 = int(input('Digite o segundo número: '))
if numero1 > numero2 : print(f'O maior número é o {numero1}') 
else : print (f'O maior número é o {numero2}')
